export function userError(error:unknown):string{
 const text=String(error||'')
 if(/REVIEW_QUEUE_FULL|CHART_BUSY/.test(text))return '正在准备复核数据，请稍后重试。'
 if(/REVIEW_SOURCE_CHANGED/.test(text))return '来源内容已变化，请重新打开并分析；旧标记不会用于新内容。'
 if(/CHART_NOT_READY/.test(text))return '等待完整 FFT 窗口，并暂停游标后重试导出。'
 if(/STALE_CHART_EXPORT/.test(text))return '分析图已过期或来源已切换，请重新导出。'
 if(/MARKER_LIMIT/.test(text))return '每份素材最多保存 512 个标记。'
 if(/INVALID_REVIEW_MARKER/.test(text))return '请检查标记名称、评论与帧范围。'
 if(/REFERENCE_MATCH_UNAVAILABLE/.test(text))return '需要来源完整、计量版本一致且范围响度与真峰值就绪；静音、缺口、估计填充、质量未知或分析未完成不能匹配。'
 if(/RETENTION_INTERRUPTED_REVIEW_SOURCE|RETENTION_RECOVERY_SAVE_FAILED|RETENTION_REPAIR_PERSIST_FAILED/.test(text))return '原始录音整理被中断，请检查文件与保存目录；可在确认后重试整理。'
 if(/REFERENCE_POSITION_OUTSIDE_RANGE/.test(text))return '游标不在比较范围内，请查看范围起点或调整偏移。'
 if(/REFERENCE_SOURCE_MISSING/.test(text))return '请先选择主素材 A 和参考 B。'
 if(/REFERENCE_SOURCE_CHANGED|REFERENCE_SOURCE_UNAVAILABLE|STALE_REFERENCE_SOURCE/.test(text))return '参考来源已变化或不可用，请重新选择。'
 if(/INVALID_REFERENCE/.test(text))return '请检查比较范围和时间偏移。'
 if(/IMPORT_QUEUE_FULL|INVALID_IMPORT_FILES/.test(text))return '一次最多准备四个素材，请等待完成或取消部分任务后重试。'
 if(/IMPORT_REQUIRES_DISK_FILE/.test(text))return '请拖入磁盘上的音频文件。'
 if(/IMPORT_INSUFFICIENT_SPACE/.test(text))return '素材缓存空间不足，请释放磁盘空间后重试；原文件保持不变。'
 if(/UNSUPPORTED_IMPORT_STREAMS/.test(text))return '请选择只有一条音轨的音频文件；暂不支持视频或多音轨素材。'
 if(/UNSUPPORTED_IMPORT_CODEC|UNSUPPORTED_IMPORT_FORMAT/.test(text))return '支持单/双声道、8–96 kHz 的 WAV 16/24-bit 或 float32、MP3、AAC-LC；请检查文件格式。'
 if(/IMPORT_RELOCATE_CONTENT_CHANGED/.test(text))return '所选文件与原素材内容不同，请另行导入；重新定位需要相同内容。'
 if(/IMPORT_SOURCE_INSIDE_CACHE/.test(text))return '这是 Trace 管理的缓存，请从文件库查看已有素材。'
 if(/IMPORT_SOURCE_CHANGED/.test(text))return '原文件内容已变化，请点击“更新素材”重新准备。'
 if(/IMPORT_NOT_READY|IMPORT_SOURCE_BUSY/.test(text))return '素材还在准备或收尾，请完成后再试。'
 if(/IMPORT_DECODED_CACHE_CHANGED|IMPORT_CACHE_IDENTITY_CHANGED|IMPORT_CACHE_FRAME_MISMATCH/.test(text))return '素材缓存需要重建，请点击“重新准备”；原文件保持不变。'
 if(/IMPORT_CACHE_HAS_UNKNOWN_FILES|INVALID_IMPORT_CACHE_DIRECTORY/.test(text))return '缓存目录含未知文件或链接，已保留内容，请检查素材目录后再清理。'
 if(/REPORT_QUEUE_FULL/.test(text))return '最多同时保留两项待生成报告，请等待完成或取消一项。'
 if(/SAVE_CACHE_BEFORE_REPORT/.test(text))return '请先保存缓存，再生成测量报告。'
 if(/REPORT_SOURCE_NOT_OPEN/.test(text))return '请先打开这份报告对应的文件，再定位事件。'
 if(/UNKNOWN_REPORT/.test(text))return '临时报告已清理，请重新生成。'
 if(/REPORT_CANCELLED/.test(text))return '报告任务已取消；已有报告和原音频保持不变。'
 if(/REPORT_NOT_READY|REPORT_SOURCE_BUSY|REPORT_BUSY/.test(text))return '报告或来源仍在处理中，请完成后重试。'
 if(/REPORT_WORKER_EXIT/.test(text))return '报告生成未完成，请重试；原音频和已有报告仍然保留。'
 if(/RECORDING_ACTIVE/.test(text))return '请先结束录音，再执行此操作。'
 if(/STALE_REPLAY_SOURCE|STALE_PLAYBACK_SOURCE/.test(text))return '历史来源已变化，请重新查看缓存后保存。'
  if(/CACHE_SAVE_UNAVAILABLE/.test(text))return '当前引擎不支持缓存保存，请使用完整的新版本。'
  if(/CACHE_SAVE_FRAME_MISMATCH|CACHE_SAVE_INCOMPLETE/.test(text))return '缓存保存未完整完成，已保留写入内容，可在录音文件中检查或恢复。'
  if(/INVALID_TAKE_NAME/.test(text))return '名称不能为空，且不能包含路径符号、Windows 保留名称或末尾句点。'
  if(/HISTORY_OUTSIDE_BUFFER/.test(text))return '该位置已超出最近 60 秒的精确缓存；完整历史可在结束录音后打开文件查看。'
 if(/STALE_INSPECTION_SOURCE/.test(text))return '声音来源已变化，请点击“实时”后重新定位。'
 if(/ANALYSIS_QUEUE_FULL|ANALYSIS_REFERENCE_LIMIT/.test(text))return '分析任务较多，请等待完成或取消部分任务后重新查看。'
 if(/REPLAY_EMPTY|REPLAY_NOT_READY/.test(text))return '还没有可回听的缓存，请先开始实时监测。'
 if(/LIBRARY_IDENTITY_CHANGED|INVALID_LIBRARY_PATH/.test(text))return '该目录的会话身份或位置已变化，已取消移除，请打开目录核对。'
 if(/LIBRARY_BUSY/.test(text))return '请先结束录音、文件处理或导出，再管理文件。'
 if(/ENOENT|ENOTDIR/.test(text))return '文件已移除或移动，请刷新录音文件列表。'
 if(/PUBLISH_NEW_FILE_FAILED.*(?:183|80)\)/.test(text))return '目标位置已有同名文件，请使用其他文件名。'
 if(/DISK_BACKPRESSURE/.test(text))return '录音已停止：磁盘未能及时写入，已保留可用录音。'
 if(/DISK_|WAV_WRITE|WAV_FLUSH|ENOSPC/.test(text))return '文件写入未完成，请检查磁盘空间和保存目录。'
 if(/DEVICE_UNAVAILABLE|DEVICE_INVALIDATED|PLAYBACK_ACTIVATE|PLAYBACK_INITIALIZE/.test(text))return '音频设备暂不可用，请重新连接或选择其他设备。'
 if(/PLAYBACK_UNDERRUN/.test(text))return '回听已停止：未能及时读取音频。请重新打开文件后重试。'
 if(/RECORD_SNAPSHOT_FAILED/.test(text))return '录音数据更新失败，已停止本次录音并保留已写入的文件。请重新连接后重试。'
 if(/FILE_SNAPSHOT_FAILED|CORRUPT_CACHE|DECODED_CACHE/.test(text))return '文件分析或回听缓存需要重新准备，请重新打开文件。'
 if(/EXPORTED_FILE_CHANGED/.test(text))return '成品文件已被修改，请从原始录音重新导出。'
 if(/RETENTION_SOURCE_CHANGED/.test(text))return '原始文件已发生变化，已保留文件，请手动核对。'
 if(/SOURCE_CHANGED|HASH_SOURCE_CHANGED/.test(text))return '来源文件在处理期间发生变化，请重新检查文件后重试。'
 if(/ENCODER_BUILD_CHANGED|DECODER_BUILD_CHANGED/.test(text))return '媒体处理组件版本不匹配，请重新解压完整的 Trace 软件包。'
 if(/EXPORT_QUEUE_FULL/.test(text))return '等待处理的导出较多，请稍后重试。'
 if(/EXPORT_ACTIVE/.test(text))return '请先完成或取消当前导出，再修改录音目录。'
 if(/ASSET_NOT_READY|EXPORT_NOT_READY|ANALYSIS_NOT_READY/.test(text))return '文件还在准备中，请稍后再试。'
 if(/MEDIA_PROCESS_FAILED|FILE_WORKER_EXIT/.test(text))return '媒体处理未完成，可重试；原始录音仍然保留。'
 if(/PUBLISH_NEW_FILE_FAILED|EACCES|EPERM|WAV_CREATE_FAILED/.test(text))return '无法保存到该位置，请检查目录权限或文件是否被占用。'
 if(/INVALID_|UNSUPPORTED_/.test(text))return '设置或文件格式不受支持，请检查所选选项。'
 if(/RECOVERED_UNKNOWN_TAIL/.test(text))return '已恢复完整写入的部分，末尾未写入的内容无法确认。'
 if(/^[\u3400-\u9fff]/u.test(text))return text
 return '操作未完成，请重试。技术详情可用于进一步排查。'
}
